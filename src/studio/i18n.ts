export function getLang(): StudioLanguage {
  return studioSettings.get().language || "az";
}

export function t(key: string): string {
  const lang = getLang();
  return DICT[lang]?.[key] || DICT.en[key] || DICT.az[key] || key;
}

export function applyI18nToStaticDom(hasOpenProject: boolean): void {
  const lang = getLang();
  document.documentElement.lang = lang;

  const searchInput = document.getElementById("studio-search-input") as HTMLInputElement | null;
  if (searchInput) searchInput.placeholder = t("searchPlaceholder");

  const expTitle = document.querySelector("#studio-left-panel .panel-header-title");
  if (expTitle) expTitle.textContent = t("explorer");

  const projLabel = document.getElementById("current-project-label");
  if (projLabel && !hasOpenProject) {
    projLabel.textContent = t("openFolder");
  }

  const statusLeft = document.getElementById("status-left-text");
  if (statusLeft && ["Hazır", "Ready", "Готово"].includes(statusLeft.textContent || "")) {
    statusLeft.textContent = t("ready");
  }

  const railTitles: Record<string, string> = {
    "rail-btn-explorer": t("explorer"),
    "rail-btn-search": `${t("search")} (Ctrl+Shift+F)`,
    "rail-btn-models": t("models"),
    "rail-btn-mcp": t("mcpServers"),
    "rail-btn-extensions": t("extensions"),
    "rail-btn-api": t("apiTester"),
    "rail-btn-preview": t("previewPortsNav"),
    "rail-btn-data": t("dataExplorerNav"),
    "rail-btn-terminal": `${t("terminal")} (Ctrl+\`)`,
    "rail-btn-chat": `Mintu AI (Ctrl+L)`,
    "rail-btn-settings": t("settings"),
    "btn-topbar-settings": t("settings"),
  };
  for (const [id, title] of Object.entries(railTitles)) {
    const el = document.getElementById(id);
    if (el) el.title = title;
  }
}
